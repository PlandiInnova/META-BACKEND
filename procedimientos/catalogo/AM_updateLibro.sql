DROP PROCEDURE IF EXISTS AM_updateLibro;
DELIMITER $$
CREATE PROCEDURE AM_updateLibro
(
    IN IDLIBRO INT,
    IN IDSEMESTRE INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255),
    IN ISBN VARCHAR(50),
    IN AUTORES VARCHAR(200),
    IN LINK VARCHAR(100)
)
BEGIN
    IF EXISTS(SELECT 1 FROM CAT_LIBRO WHERE LIB_ID = IDLIBRO) THEN
        IF EXISTS(SELECT 1 FROM CAT_SEMESTRE WHERE SEM_ID = IDSEMESTRE AND SEM_STATUS = 1
        ) THEN
            UPDATE CAT_LIBRO
            SET LIB_NOMBRE = NOMBRE, LIB_SEM_ID = IDSEMESTRE, LIB_PORTADA = PORTADA, LIB_ISBN = ISBN, LIB_AUTORES = AUTORES, LIB_LINK = LINK WHERE LIB_ID = IDLIBRO;
            SELECT 1 RESPONSE, 'LIBRO ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
        ELSE
            SELECT 0 RESPONSE, 'EL SEMESTRE NO EXISTE O ESTA INACTIVO' DESCRIPCION;
        END IF;
    ELSE
        SELECT 0 RESPONSE, 'EL LIBRO NO EXISTE' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
