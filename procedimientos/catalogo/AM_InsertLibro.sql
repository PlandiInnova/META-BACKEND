DROP PROCEDURE IF EXISTS AM_InsertLibro;
DELIMITER $$
CREATE PROCEDURE AM_InsertLibro
(
    IN IDSEMESTRE INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255),
    IN ISBN VARCHAR(50),
    IN AUTORES VARCHAR(200),
    IN LINK VARCHAR(100)
)
BEGIN
    IF EXISTS(
        SELECT 1
        FROM CAT_SEMESTRE
        WHERE SEM_ID = IDSEMESTRE
        AND SEM_STATUS = 1
    ) THEN
        INSERT INTO CAT_LIBRO(LIB_NOMBRE,LIB_SEM_ID,LIB_PORTADA,LIB_ISBN,LIB_AUTORES,LIB_LINK,LIB_STATUS)
        VALUES(NOMBRE,IDSEMESTRE,PORTADA,ISBN,AUTORES,LINK,1);
        SELECT LAST_INSERT_ID() RESPONSE, 'LIBRO INSERTADO CORRECTAMENTE' DESCRIPCION;
    ELSE
        SELECT 0 RESPONSE,'EL SEMESTRE NO EXISTE O ESTA INACTIVO' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
