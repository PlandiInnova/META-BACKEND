DROP PROCEDURE IF EXISTS AM_getLibros;
DELIMITER $$
CREATE PROCEDURE AM_getLibros
(
IN IDSEMESTRE VARCHAR(100)
)
BEGIN
IF EXISTS(SELECT 1 FROM CAT_LIBRO WHERE IDSEMESTRE IS NULL OR LIB_SEM_ID = IDSEMESTRE) THEN
 SELECT
        l.LIB_ID AS id,
        l.LIB_NOMBRE AS nombre,
        l.LIB_PORTADA AS portada,
        l.LIB_STATUS AS status,
        l.LIB_SEM_ID AS padre_id,
        CONCAT_WS(' / ', sb.SUB_NOMBRE, s.SEM_NOMBRE) AS padre_nombre,
        l.LIB_ISBN AS isbn,
        l.LIB_AUTORES AS autores,
        l.LIB_LINK AS link
    FROM CAT_LIBRO l
    LEFT JOIN CAT_SEMESTRE s ON s.SEM_ID = l.LIB_SEM_ID
    LEFT JOIN CAT_SUBSISTEMA sb ON sb.SUB_ID = s.SEM_SUB_ID
    WHERE IDSEMESTRE IS NULL OR l.LIB_SEM_ID = IDSEMESTRE
    ORDER BY l.LIB_SEM_ID, l.LIB_ID;
ELSE
SELECT "0" RESPONSE,"NO HAY LIBROS" DESCRIPCION;
END IF;
END$$
DELIMITER ;
