DROP PROCEDURE IF EXISTS AM_updateStatus;
DELIMITER $$
CREATE PROCEDURE AM_updateStatus
(
    IN TIPO VARCHAR(20),
    IN ID INT,
    IN ESTATUS INT
)
BEGIN
    IF TIPO = 'subsistema' AND EXISTS(SELECT 1 FROM CAT_SUBSISTEMA WHERE SUB_ID = ID) THEN
        UPDATE CAT_SUBSISTEMA SET SUB_STATUS = ESTATUS WHERE SUB_ID = ID;
        SELECT 1 RESPONSE, 'STATUS ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
    ELSEIF TIPO = 'semestre' AND EXISTS(SELECT 1 FROM CAT_SEMESTRE WHERE SEM_ID = ID) THEN
        UPDATE CAT_SEMESTRE SET SEM_STATUS = ESTATUS WHERE SEM_ID = ID;
        SELECT 1 RESPONSE, 'STATUS ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
    ELSEIF TIPO = 'libro' AND EXISTS(SELECT 1 FROM CAT_LIBRO WHERE LIB_ID = ID) THEN
        UPDATE CAT_LIBRO SET LIB_STATUS = ESTATUS WHERE LIB_ID = ID;
        SELECT 1 RESPONSE, 'STATUS ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
    ELSE
        SELECT 0 RESPONSE, 'EL REGISTRO NO EXISTE' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
