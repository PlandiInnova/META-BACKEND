DROP PROCEDURE IF EXISTS AM_updateSemestre;
DELIMITER $$
CREATE PROCEDURE AM_updateSemestre
(
    IN IDSEMESTRE INT,
    IN IDSUBSISTEMA INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255)
)
BEGIN
    IF EXISTS( SELECT 1 FROM CAT_SEMESTRE WHERE SEM_ID = IDSEMESTRE) THEN
        IF EXISTS( SELECT 1 FROM CAT_SUBSISTEMA WHERE SUB_ID = IDSUBSISTEMA AND SUB_STATUS = 1) THEN
            UPDATE CAT_SEMESTRE
            SET SEM_SUB_ID = IDSUBSISTEMA, SEM_NOMBRE = NOMBRE, SEM_PORTADA = PORTADA
            WHERE SEM_ID = IDSEMESTRE;
            SELECT 1 RESPONSE,'SEMESTRE ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
        ELSE
            SELECT 0 RESPONSE, 'EL SUBSISTEMA NO EXISTE O ESTA INACTIVO' DESCRIPCION;
        END IF;
    ELSE
        SELECT 0 RESPONSE, 'EL SEMESTRE NO EXISTE' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
