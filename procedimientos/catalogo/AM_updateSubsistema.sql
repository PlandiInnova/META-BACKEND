DROP PROCEDURE IF EXISTS AM_updateSubsistema;
DELIMITER $$
CREATE PROCEDURE AM_updateSubsistema
(
    IN IDSUBSISTEMA INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA LONGTEXT,
    IN COLOR VARCHAR(7)
)
BEGIN
    IF EXISTS(SELECT 1 FROM CAT_SUBSISTEMA WHERE SUB_ID = IDSUBSISTEMA AND SUB_STATUS = 1) THEN
        UPDATE CAT_SUBSISTEMA SET SUB_NOMBRE = NOMBRE, SUB_PORTADA = PORTADA, SUB_COLOR = COLOR WHERE SUB_ID = IDSUBSISTEMA;
        SELECT
            1 RESPONSE,
            'SUBSISTEMA ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
    ELSE
        SELECT
            0 RESPONSE,
            'EL SUBSISTEMA NO EXISTE O ESTA INACTIVO' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
