DROP PROCEDURE IF EXISTS AM_updateSubsistema;
DELIMITER $$
CREATE PROCEDURE AM_updateSubsistema
(
    IN IDSUBSISTEMA INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255)
)
BEGIN
    IF EXISTS(SELECT 1 FROM CAT_SUBSISTEMA WHERE SUB_ID = IDSUBSISTEMA) THEN
        UPDATE CAT_SUBSISTEMA SET SUB_NOMBRE = NOMBRE, SUB_PORTADA = PORTADA WHERE SUB_ID = IDSUBSISTEMA;
        SELECT
            1 RESPONSE,
            'SUBSISTEMA ACTUALIZADO CORRECTAMENTE' DESCRIPCION;
    ELSE
        SELECT
            0 RESPONSE,
            'EL SUBSISTEMA NO EXISTE' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
