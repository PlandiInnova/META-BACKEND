DROP PROCEDURE IF EXISTS AM_InsertSubsistema;
DELIMITER $$
CREATE PROCEDURE AM_InsertSubsistema
(
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255)
)
BEGIN
    INSERT INTO CAT_SUBSISTEMA (SUB_NOMBRE, SUB_PORTADA, SUB_STATUS) VALUES(NOMBRE,PORTADA,1);
    SELECT LAST_INSERT_ID() RESPONSE, 'SUBSISTEMA INSERTADO CORRECTAMENTE' DESCRIPCION;
END$$
DELIMITER ;
