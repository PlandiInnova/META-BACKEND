DROP PROCEDURE IF EXISTS AM_InsertSemestre;
DELIMITER $$
CREATE PROCEDURE AM_InsertSemestre
(
    IN IDSUBSISTEMA INT,
    IN NOMBRE VARCHAR(100),
    IN PORTADA VARCHAR(255)
)
BEGIN
    IF EXISTS(
        SELECT 1
        FROM CAT_SUBSISTEMA
        WHERE SUB_ID = IDSUBSISTEMA
        AND SUB_STATUS = 1
    ) THEN
        INSERT INTO CAT_SEMESTRE(SEM_SUB_ID,SEM_NOMBRE,SEM_PORTADA,SEM_STATUS) VALUES (IDSUBSISTEMA,NOMBRE,PORTADA,1);
        SELECT LAST_INSERT_ID() RESPONSE,'SEMESTRE INSERTADO CORRECTAMENTE' DESCRIPCION;
    ELSE
        SELECT 0 RESPONSE,'EL SUBSISTEMA NO EXISTE O ESTA INACTIVO' DESCRIPCION;
    END IF;
END$$
DELIMITER ;
