DROP PROCEDURE IF EXISTS AM_getSubsistemas;
DELIMITER $$
CREATE PROCEDURE AM_getSubsistemas
(
)
BEGIN
IF EXISTS(SELECT 1 FROM CAT_SUBSISTEMA) THEN
SELECT  SUB_ID AS id,
        SUB_NOMBRE AS nombre,
        SUB_PORTADA AS portada,
        SUB_STATUS AS status,
        NULL AS padre_id,
        NULL AS padre_nombre FROM CAT_SUBSISTEMA
        ORDER BY SUB_ID;
ELSE
SELECT "0" RESPONSE,"NO HAY SUBSISTEMAS" DESCRIPCION;
END IF;
END$$
DELIMITER ;
