DROP PROCEDURE IF EXISTS AM_validarUsuAdmin;
DELIMITER $$
CREATE PROCEDURE AM_validarUsuAdmin
(
IN USUARIO VARCHAR(100),
IN PASS VARCHAR(100)
)
BEGIN
IF EXISTS(SELECT * FROM CAT_USUARIO_ADMIN WHERE USU_USUARIO = BINARY USUARIO AND USU_PASSWORD = BINARY PASS) THEN
SET @estado=(SELECT USU_STATUS FROM CAT_USUARIO_ADMIN WHERE USU_USUARIO = BINARY USUARIO AND USU_PASSWORD = BINARY PASS);
IF(@estado = 1) THEN
SELECT *, "1" RESPONSE FROM CAT_USUARIO_ADMIN WHERE USU_USUARIO = BINARY USUARIO AND USU_PASSWORD = BINARY PASS;
ELSE
SELECT "2" RESPONSE,"Usuario desactivado" DESCRIPCION;
END IF;
ELSE
SELECT "0" RESPONSE,"Usuario no existe" DESCRIPCION;
END IF;
END$$
DELIMITER ;
