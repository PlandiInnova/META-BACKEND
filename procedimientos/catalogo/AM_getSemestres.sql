DROP PROCEDURE IF EXISTS AM_getSemestres;
DELIMITER $$
CREATE PROCEDURE AM_getSemestres
(
IN IDSUBSISTEMA VARCHAR(100)
)
BEGIN
IF EXISTS(SELECT 1 FROM CAT_SEMESTRE WHERE IDSUBSISTEMA IS NULL OR SEM_SUB_ID = IDSUBSISTEMA) THEN
 SELECT
        s.SEM_ID AS id,
        s.SEM_NOMBRE AS nombre,
        s.SEM_PORTADA AS portada,
        s.SEM_STATUS AS status,
        s.SEM_SUB_ID AS padre_id,
        sb.SUB_NOMBRE AS padre_nombre
    FROM CAT_SEMESTRE s
    LEFT JOIN CAT_SUBSISTEMA sb ON sb.SUB_ID = s.SEM_SUB_ID
    WHERE IDSUBSISTEMA IS NULL OR s.SEM_SUB_ID = IDSUBSISTEMA
    ORDER BY s.SEM_SUB_ID, s.SEM_ID;
ELSE
SELECT "0" RESPONSE,"NO HAY SEMESTRES" DESCRIPCION;
END IF;
END$$
DELIMITER ;
